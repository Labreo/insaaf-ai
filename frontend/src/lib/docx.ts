// Minimal, valid .docx writer (OOXML) with JSZip. No template library, no server.
import JSZip from 'jszip'
import type { Draft, Matter } from './types'

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

function p(text: string, opts: { bold?: boolean; italic?: boolean; size?: number; align?: 'center' | 'both'; color?: string } = {}) {
  const rPr = [opts.bold && '<w:b/>', opts.italic && '<w:i/>', opts.size && `<w:sz w:val="${opts.size}"/>`, opts.color && `<w:color w:val="${opts.color}"/>`].filter(Boolean).join('')
  const pPr = opts.align ? `<w:pPr><w:jc w:val="${opts.align}"/></w:pPr>` : ''
  return `<w:p>${pPr}<w:r><w:rPr>${rPr}</w:rPr><w:t xml:space="preserve">${esc(text)}</w:t></w:r></w:p>`
}

export async function draftToDocx(matter: Matter, draft: Draft): Promise<Blob> {
  const body = [
    p(draft.type.replace(/_/g, ' ').toUpperCase(), { bold: true, size: 28, align: 'center' }),
    p(matter.title.replace(' (FICTIONAL)', ''), { italic: true, align: 'center' }),
    p(''),
    ...draft.paragraphs.flatMap((para, i) => [
      p(`${i + 1}. ${para.locked_out_claim ? '[No verified authority found — claim removed by Authority Lock]' : para.text}`, { color: para.locked_out_claim ? 'B23A32' : undefined }),
      ...(para.sources.length ? [p(`   Authority: ${para.sources.map((s) => `${s.title}${s.paragraph !== '—' ? `, para ${s.paragraph}` : ''}`).join('; ')}`, { italic: true, size: 18, color: '666666' })] : []),
    ]),
    p(''),
    p(draft.watermark, { italic: true, size: 18, color: '8A6D3B' }),
    p(`Generated by Insaaf · model ${draft.model_version} · ${new Date().toLocaleString('en-IN')} · FICTIONAL DEMO MATTER`, { size: 16, color: '888888' }),
  ].join('')

  const document = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>${body}<w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440"/></w:sectPr></w:body></w:document>`

  const zip = new JSZip()
  zip.file('[Content_Types].xml', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>`)
  zip.file('_rels/.rels', `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>`)
  zip.file('word/document.xml', document)
  return zip.generateAsync({ type: 'blob', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' })
}

export function download(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob)
  const a = Object.assign(document.createElement('a'), { href: url, download: name })
  document.body.appendChild(a); a.click(); a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 2000)
}
